#!/usr/bin/env python3
"""DiffusionNFT LoRA trainer for the native Wan2.2-TI2V-5B DiT (cached inputs), single- or multi-node DDP.

Online RL via the forward process (Zheng et al., DiffusionNFT; loss as in NVlabs/DiffusionNFT
scripts/train_nft_sd3.py). Per sample (generated by the sampling ("old") policy, reward advantage A) and per drawn
timestep/noise (native FlowMatch state, x_t = (1-s) x0 + s eps, v target = eps - x0):
    r     = clamp((clip(A, +-C) / C) / 2 + 0.5, 0, 1)
    v+    = b v_theta + (1-b) v_old            v- = (1+b) v_old - b v_theta
    x0+-  = x_t - s v+-                        w+- = mean|x0+- - x0| (detached, >= 1e-5)
    L     = C/b * [ r mean((x0+ - x0)^2 / w+) + (1-r) mean((x0- - x0)^2 / w-) ] + kl * mean((v_theta - v_ref)^2)
v_ref = frozen base (adapters disabled); v_old = the policy that generated the round's data (the --init-lora adapters
held fixed during the round; equal to v_ref when training starts from the base). The conditioning (first) latent
frame is excluded from every term. Re-uses the verified E3 trainer pieces.
"""
import argparse
import contextlib
import json
from pathlib import Path
import sys
import time

sys.path.insert(0, str(Path(__file__).resolve().parent))
import train_e3_lora as tr  # noqa: E402

require = tr.require


def reward_weight(advantage, clip_max):
    """Official normalisation of a clipped advantage to the optimality probability r in [0, 1]."""
    a = max(-clip_max, min(clip_max, float(advantage)))
    return min(1.0, max(0.0, (a / clip_max) / 2.0 + 0.5))


def nft_terms(v, v_old, v_ref, xt, x0, sigma, r, beta, clip_max, kl_beta):
    """All tensors float32 with identical shape (first frame already removed); returns dict of scalars."""
    import torch
    pos = beta * v + (1.0 - beta) * v_old
    neg = (1.0 + beta) * v_old - beta * v
    x0p = xt - sigma * pos
    x0n = xt - sigma * neg
    with torch.no_grad():
        wp = (x0p.double() - x0.double()).abs().mean().clamp(min=1e-5)
        wn = (x0n.double() - x0.double()).abs().mean().clamp(min=1e-5)
    pos_loss = ((x0p - x0) ** 2 / wp).mean()
    neg_loss = ((x0n - x0) ** 2 / wn).mean()
    policy = (r * pos_loss / beta + (1.0 - r) * neg_loss / beta) * clip_max
    kl = ((v - v_ref) ** 2).mean()
    return dict(total=policy + kl_beta * kl, policy=policy.detach(), kl=kl.detach(), pos=pos_loss.detach(),
                neg=neg_loss.detach(), old_deviate=((v - v_old) ** 2).mean().detach())


@contextlib.contextmanager
def swapped(params, values):
    """Temporarily load other adapter values (no autograd); restores the live values exactly."""
    import torch
    with torch.no_grad():
        live = [p.detach().clone() for p in params]
        for p, v in zip(params, values):
            p.copy_(v)
    try:
        yield
    finally:
        with torch.no_grad():
            for p, v in zip(params, live):
                p.copy_(v)


def load_init_lora(path, pipe):
    """Exported LoRA (export_lora format, same adapter names) -> live adapters; returns detached GPU copies."""
    import torch
    from safetensors.torch import load_file
    tensors = load_file(str(path))
    adapters = tr.ts.trainable_adapters(pipe.dit)
    require(set(tensors) == set(adapters), 'Init LoRA adapter names differ')
    with torch.no_grad():
        for k, p in adapters.items():
            require(tensors[k].shape == p.shape, 'Init LoRA shape differs: ' + k)
            p.copy_(tensors[k].to(p.device, p.dtype))
    return [p.detach().clone() for p in adapters.values()]


def load_round(samples_path, cache_index, check_shard=None):
    idx = tr.load_cache_index(cache_index, 'nft', check_shard=check_shard)
    by_id = {e['sample_id']: e for e in idx['samples']}
    rows = [json.loads(l) for l in Path(samples_path).read_text().splitlines() if l.strip()]
    require(rows and len({r['sample_id'] for r in rows}) == len(rows), 'Empty/duplicate round samples')
    require(all(r['sample_id'] in by_id and isinstance(r['advantage'], float) for r in rows),
            'Every round sample needs a cached entry and a float advantage')
    return [(by_id[r['sample_id']], r['advantage']) for r in rows], idx


def sample_losses(pipe, sample, adv, tid, noise, a, old, params, autocast):
    import torch
    inputs = tr.cached_inputs(sample, pipe.device, offload=False)
    timestep, latents, _ = tr.native_state(pipe, inputs, tid, noise)
    sigma = float(pipe.scheduler.sigmas[tid])
    base_inputs = dict(inputs, use_gradient_checkpointing=False, use_gradient_checkpointing_offload=False)
    with torch.no_grad(), tr.adapters_disabled(pipe.dit), autocast():
        v_ref = tr.predict(pipe, base_inputs, latents.clone(), timestep)[:, :, 1:].float()
    if old is None:
        v_old = v_ref
    else:
        with torch.no_grad(), swapped(params, old), autocast():
            v_old = tr.predict(pipe, base_inputs, latents.clone(), timestep)[:, :, 1:].float()
    with autocast():
        v = tr.predict(pipe, inputs, latents, timestep)[:, :, 1:].float()
    x0 = inputs['input_latents'][:, :, 1:].float()
    xt = latents[:, :, 1:].float()
    r = reward_weight(adv, a.adv_clip_max)
    out = nft_terms(v, v_old, v_ref, xt, x0, sigma, r, a.nft_beta, a.adv_clip_max, a.kl_beta)
    out['r'] = r
    return out


def parser():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--samples', required=True); ap.add_argument('--cache-index', required=True)
    ap.add_argument('--out-dir', type=Path, required=True)
    ap.add_argument('--models-dir', type=Path, required=True); ap.add_argument('--framework', type=Path, default=tr.FRAMEWORK_DEFAULT)
    ap.add_argument('--init-lora', type=Path, help='round k>0: adapters of the sampling policy (also v_old)')
    ap.add_argument('--max-steps', type=int, required=True); ap.add_argument('--seed', type=int, default=20261123)
    ap.add_argument('--lr', type=float, default=1e-4); ap.add_argument('--warmup', type=int, default=5)
    ap.add_argument('--weight-decay', type=float, default=1e-4); ap.add_argument('--clip', type=float, default=1.0)
    ap.add_argument('--nft-beta', type=float, default=1.0); ap.add_argument('--adv-clip-max', type=float, default=5.0)
    ap.add_argument('--kl-beta', type=float, default=1e-4)
    ap.add_argument('--max-gpu-hours', type=float, required=True)
    ap.add_argument('--multi-nodes', type=int, default=1, help='user-authorized N nodes x 8 ranks')
    return ap


def validate(a):
    require(a.max_steps > a.warmup >= 0 and a.lr > 0 and a.clip > 0 and a.weight_decay >= 0, 'Bad optimizer settings')
    require(0 < a.nft_beta <= 1.0 and a.adv_clip_max > 0 and a.kl_beta >= 0, 'Bad NFT settings')


def main():
    a = parser().parse_args()
    validate(a)
    import torch
    comm = tr.setup_distributed(multi_nodes=a.multi_nodes)
    started = time.monotonic()
    out = a.out_dir
    if comm.rank == 0:
        require(not out.exists(), 'New --out-dir required')
        (out / 'private').mkdir(parents=True); (out / 'export').mkdir()
    comm.barrier()
    data, idx = load_round(a.samples, a.cache_index, check_shard=(comm.rank, comm.world))
    allocation = tr.budget(a.max_gpu_hours, comm.world, 60, 240, 120, multi_nodes=a.multi_nodes)
    shards = tr.verify_base_shards(a.models_dir, hash_content=(comm.rank == 0))
    pipe = tr.build_pipe(str(a.framework), shards, a.seed, device=comm.device)
    frozen_before = tr.ts.frozen_state_hash(pipe.dit) if comm.rank == 0 else None
    if a.multi_nodes > 1:
        tr.require_same_frozen_base_across_nodes(comm, pipe, frozen_before)
    params = tr.adapter_list(pipe.dit)
    old = load_init_lora(a.init_lora, pipe) if a.init_lora else None
    init_checks = [r[0] for r in comm.gather([tr.adapter_checksum(params)])]
    require(len(set(init_checks)) == 1, 'Initial adapters differ across DDP ranks')
    optimizer = torch.optim.AdamW(params, lr=a.lr, weight_decay=a.weight_decay)
    order = tr.DataOrder(a.seed, len(data))
    autocast = lambda: torch.autocast(device_type='cuda', dtype=torch.bfloat16)  # noqa: E731
    log = open(out / 'progress.jsonl', 'a') if comm.rank == 0 else None
    estimate, stop, step = 120.0, None, 0
    for step in range(a.max_steps):
        if comm.any_flag(tr.should_stop(comm.max_duration(time.monotonic() - started), estimate, allocation)):
            stop = 'budget_exhausted_before_max_steps'; break
        t0 = time.perf_counter()
        index = order.index(step, comm.rank, comm.world)
        entry, adv = data[index]
        sample = tr.load_sample(entry)
        tid, noise = tr.draw_t_noise(a.seed, step, index, sample['x0'].shape)
        optimizer.zero_grad(set_to_none=True)
        L = sample_losses(pipe, sample, adv, tid, noise, a, old, params, autocast)
        ok = bool(torch.isfinite(L['total']).all())
        if ok:
            L['total'].backward(); ok = tr.check_grads(pipe.dit)
        if comm.any_flag(not ok):
            raise FloatingPointError('Nonfinite NFT loss/grad at step %d' % (step + 1))
        comm.all_reduce_mean_([p.grad for p in params])
        lr = a.lr * tr.lr_factor(step + 1, a.warmup, a.max_steps)
        for g in optimizer.param_groups:
            g['lr'] = lr
        gn = float(torch.nn.utils.clip_grad_norm_(params, max_norm=a.clip, error_if_nonfinite=True))
        optimizer.step(); torch.cuda.synchronize()
        sec = time.perf_counter() - t0
        estimate = max(estimate if step else 0, comm.max_duration(sec))
        keys = ('total', 'policy', 'kl', 'pos', 'neg', 'old_deviate')
        rows = comm.gather([float(L[k]) for k in keys] + [L['r'], tid])
        if log:
            n = len(rows)
            log.write(json.dumps(dict(step=step + 1, lr=lr, grad_norm=gn, seconds=sec,
                                      **{k: sum(r[i] for r in rows) / n for i, k in enumerate(keys)},
                                      r_mean=sum(r[len(keys)] for r in rows) / n)) + '\n'); log.flush()
    completed = step + 1 if stop is None else step
    checks = [r[0] for r in comm.gather([tr.adapter_checksum(params)])]
    require(len(set(checks)) == 1, 'Adapters differ across DDP ranks')
    comm.barrier()
    if comm.rank == 0:
        state = tr.checkpoint_state(pipe.dit, optimizer, completed, dict(algo='diffusion_nft', nft_beta=a.nft_beta,
                                    adv_clip_max=a.adv_clip_max, kl_beta=a.kl_beta, lr=a.lr, steps=completed), cuda=True)
        rec = tr.save_checkpoint(out / 'private' / tr.CKPT_NAME, state)
        export = tr.export_lora(out / 'export' / 'nft_lora.safetensors', state['adapters'])
        frozen_after = tr.ts.frozen_state_hash(pipe.dit)
        require(frozen_after == frozen_before, 'Frozen base changed')
        (out / 'summary.json').write_text(json.dumps(dict(
            status='completed' if stop is None else 'stopped', stop_reason=stop, completed_steps=completed,
            samples=len(data), cache_index_sha256=idx['index_sha256'], init_lora=str(a.init_lora) if a.init_lora else None,
            nft_beta=a.nft_beta, adv_clip_max=a.adv_clip_max, kl_beta=a.kl_beta, lr=a.lr, world=comm.world,
            multi_nodes=a.multi_nodes, checkpoint=rec, export=export, frozen_base_sha256=frozen_after,
            adapter_checksum_all_ranks=checks, elapsed_seconds=time.monotonic() - started), indent=1))
    comm.barrier()
    require(stop is None, 'Stopped before --max-steps: ' + str(stop))


if __name__ == '__main__':
    main()
